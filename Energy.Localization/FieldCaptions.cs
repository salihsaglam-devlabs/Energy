    public static IReadOnlyDictionary<string, string> ForCulture(CultureInfo? culture)
    {
        var name = culture?.Name ?? string.Empty;
        return name.StartsWith("tr", StringComparison.OrdinalIgnoreCase) ? Tr : En;
    }

